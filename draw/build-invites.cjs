'use strict';
/*
 * Build this year's private invites.
 *
 *   node draw/build-invites.cjs private/roster.json
 *
 * Reads the PRIVATE roster (names, branches, photos, quips, past pairs), runs the
 * draw, and writes:
 *   - envelopes.js            PUBLIC. One AES-GCM envelope per cousin, locked with
 *                             that cousin's link token. Holds no names or pairs in
 *                             plain text, so it is safe to deploy.
 *   - private/invites.csv     PRIVATE. Name, branch, token and link for each cousin.
 *                             Load it into whatsapp_dispatcher.html to send links.
 *
 * Re-running makes a NEW draw and NEW tokens, and every old link stops working.
 * Only run it again before links go out, or when you deliberately want a redraw.
 */
const { readFileSync, writeFileSync, mkdirSync } = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { drawAssignments, isValidDraw } = require('./secret-santa.cjs');

const ITERATIONS = 150000;
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'; // no 0/O, 1/l/I

function makeToken(length = 10) {
  let token = '';
  for (let i = 0; i < length; i++) token += ALPHABET[crypto.randomInt(ALPHABET.length)];
  return token;
}
const lookupId = token => crypto.createHash('sha256').update('nj-id|' + token).digest('hex').slice(0, 20);

// Pad every payload to the same byte length so envelope size reveals nothing.
function padded(payload, size = 700) {
  const json = Buffer.from(JSON.stringify(payload), 'utf8');
  if (json.length > size) throw new Error('Envelope payload too large.');
  return Buffer.concat([json, Buffer.alloc(size - json.length, 0x20)]);
}

function seal(token, payload) {
  const id = lookupId(token);
  const key = crypto.pbkdf2Sync(token, 'nj-salt|' + id, ITERATIONS, 32, 'sha256');
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const body = Buffer.concat([cipher.update(padded(payload)), cipher.final(), cipher.getAuthTag()]);
  return [id, { iv: iv.toString('base64'), ct: body.toString('base64') }];
}

function open(token, envelope) {
  const id = lookupId(token);
  const key = crypto.pbkdf2Sync(token, 'nj-salt|' + id, ITERATIONS, 32, 'sha256');
  const raw = Buffer.from(envelope.ct, 'base64');
  const decipher = crypto.createDecipheriv('aes-256-gcm', key, Buffer.from(envelope.iv, 'base64'));
  decipher.setAuthTag(raw.subarray(raw.length - 16));
  return JSON.parse(Buffer.concat([decipher.update(raw.subarray(0, raw.length - 16)), decipher.final()]).toString('utf8'));
}

const csvCell = value => `"${String(value ?? '').replace(/"/g, '""')}"`;

function main(rosterFile) {
  const root = path.resolve(__dirname, '..');
  const roster = JSON.parse(readFileSync(rosterFile, 'utf8').replace(/^﻿/, ''));
  const bySlug = new Map(roster.cousins.map(c => [c.slug, c]));
  const options = {
    participantIds: roster.cousins.map(c => c.slug),
    pastPairs: roster.pastPairs,
    branchOf: Object.fromEntries(roster.cousins.map(c => [c.slug, c.branch]))
  };

  const draw = drawAssignments(options);
  if (!isValidDraw(draw, options)) throw new Error('Draw failed its own rule check.');

  const tokens = new Map();
  const used = new Set();
  for (const slug of options.participantIds) {
    let token;
    do token = makeToken(); while (used.has(token));
    used.add(token);
    tokens.set(slug, token);
  }

  const items = {};
  for (const [giverSlug, recipientSlug] of draw) {
    const giver = bySlug.get(giverSlug), recipient = bySlug.get(recipientSlug);
    const [id, envelope] = seal(tokens.get(giverSlug), {
      giverSlug, giverName: giver.name,
      recipient: { slug: recipient.slug, name: recipient.name, branch: recipient.branch, photo: recipient.photo, quip: recipient.quip }
    });
    items[id] = envelope;
  }

  // Shuffle key order so envelope position says nothing about the roster order.
  const shuffledItems = Object.fromEntries(Object.entries(items).sort(() => crypto.randomInt(3) - 1));
  const publicFile = `/* Generated by draw/build-invites.cjs. Encrypted: one envelope per private link. */\n` +
    `window.NJ_ENVELOPES = ${JSON.stringify({ v: 1, year: roster.year, iter: ITERATIONS, items: shuffledItems })};\n`;
  writeFileSync(path.join(root, 'envelopes.js'), publicFile);

  // Self-check: every token opens exactly its own envelope and the opened draw is valid.
  const reopened = new Map();
  for (const [slug, token] of tokens) {
    const data = open(token, items[lookupId(token)]);
    if (data.giverSlug !== slug) throw new Error('Envelope check failed for ' + slug);
    reopened.set(slug, data.recipient.slug);
  }
  if (!isValidDraw(reopened, options)) throw new Error('Re-opened envelopes break a rule.');

  mkdirSync(path.join(root, 'private'), { recursive: true });
  const base = roster.baseUrl.replace(/\/?$/, '/');
  const lines = [['name', 'slug', 'branch', 'token', 'link', 'phone'].map(csvCell).join(',')];
  for (const c of roster.cousins) {
    const token = tokens.get(c.slug);
    lines.push([c.name, c.slug, c.branch, token, `${base}?k=${token}`, c.phone || ''].map(csvCell).join(','));
  }
  writeFileSync(path.join(root, 'private', 'invites.csv'), '﻿' + lines.join('\n') + '\n');

  process.stdout.write(`Draw OK for ${draw.size} cousins: no self, same-branch or past-pair matches.\n` +
    `Wrote envelopes.js (public, encrypted) and private/invites.csv (keep private).\n`);
}

if (require.main === module) {
  const [rosterFile] = process.argv.slice(2);
  if (!rosterFile) {
    process.stderr.write('Usage: node draw/build-invites.cjs private/roster.json\n');
    process.exitCode = 1;
  } else {
    try { main(rosterFile); } catch (error) {
      process.stderr.write(`Build failed: ${error.message}\n`);
      process.exitCode = 1;
    }
  }
}

module.exports = { lookupId, seal, open, ITERATIONS };
